//! `openchef init`: detect installed agent CLIs and write the configuration.

use std::collections::BTreeMap;
use std::io::{BufRead as _, Write};

use anyhow::{Context as _, bail};
use openchef_config::{Config, Paths, PlanTier, Runtime, RuntimeStatus, default_config};

use crate::cli::{InitArgs, OnOff};
use crate::commands::doctor::state;
use crate::{Deps, exit};

const HEADER: &str = r#"# OpenChef configuration, generated by "openchef init".
# Reference: docs/architecture.md §7.4 (model selection) and §13 (configuration).
#
# plan_tier drives the automatic effort profile: entry plans (free, pro, plus) start at
# "economy", large plans (max, ultra) at "balanced". Change it if your plan differs.

"#;

/// Shown before asking (§10.2: init explains the probes and asks).
const PROBES_EXPLAINED: &str =
    "Usage probes let OpenChef route by how much of each plan is left. They read the
login Claude Code and Codex stored on this machine (read only; never refreshed,
stored or sent anywhere but the provider) and call the providers' usage endpoints,
which are undocumented: they may change or be disallowed at any time. Use at your
own risk.";

fn parse_plans(flags: &[String]) -> anyhow::Result<BTreeMap<Runtime, PlanTier>> {
    let mut plans = BTreeMap::new();
    for flag in flags {
        let Some((runtime, tier)) = flag.split_once('=') else {
            bail!("--plan {flag}: want RUNTIME=TIER, e.g. claude=max");
        };
        let runtime: Runtime = runtime.parse().map_err(|_| {
            let all: Vec<&str> = Runtime::ALL.iter().map(|r| r.as_str()).collect();
            anyhow::anyhow!(
                "--plan {flag}: unknown runtime {runtime:?} (want one of {})",
                all.join(", ")
            )
        })?;
        let tier: PlanTier = tier.parse().map_err(|_| {
            let all: Vec<&str> = PlanTier::ALL.iter().map(|t| t.as_str()).collect();
            anyhow::anyhow!(
                "--plan {flag}: unknown plan tier {tier:?} (want one of {})",
                all.join(", ")
            )
        })?;
        let _previous = plans.insert(runtime, tier);
    }
    Ok(plans)
}

/// The flag, else the user's answer on a terminal (default yes), else on.
fn probe_consent(
    out: &mut dyn Write,
    deps: &Deps,
    flag: Option<OnOff>,
    dry_run: bool,
) -> anyhow::Result<bool> {
    match flag {
        Some(OnOff::On) => return Ok(true),
        Some(OnOff::Off) => return Ok(false),
        None => {}
    }
    if dry_run || !deps.interactive {
        return Ok(true);
    }
    write!(out, "{PROBES_EXPLAINED}\nEnable usage probes? [Y/n] ")?;
    out.flush()?;
    let mut answer = String::new();
    let _bytes = std::io::stdin()
        .lock()
        .read_line(&mut answer)
        .context("read answer")?;
    Ok(matches!(
        answer.trim().to_lowercase().as_str(),
        "" | "y" | "yes"
    ))
}

pub(crate) fn run(
    out: &mut dyn Write,
    deps: &Deps,
    paths: &Paths,
    args: &InitArgs,
) -> anyhow::Result<i32> {
    let plans = parse_plans(&args.plans)?;
    let (usable, skipped): (Vec<RuntimeStatus>, Vec<RuntimeStatus>) = deps
        .detector
        .detect()
        .into_iter()
        .partition(RuntimeStatus::usable);
    if usable.is_empty() {
        bail!(
            "no usable agent CLI found: install and log in to at least one of claude, codex or agy, then run `openchef doctor`"
        );
    }
    let runtimes: Vec<Runtime> = usable.iter().map(|s| s.runtime).collect();
    let mut config = default_config(&runtimes, &plans);
    let probes = probe_consent(out, deps, args.quota_probes, args.dry_run)?;
    config.quota.probes = Some(probes);
    let text = format!("{HEADER}{}", config.to_toml()?);
    let _check = Config::parse(&text).context("generated configuration is invalid (bug)")?;

    if args.dry_run {
        write!(out, "{text}")?;
        return Ok(exit::OK);
    }
    if paths.config.exists() && !args.force {
        bail!(
            "configuration already exists at {} (use --force to overwrite, or --dry-run to preview)",
            paths.config.display()
        );
    }
    paths.ensure_dirs()?;
    config.save_with_header(&paths.config, HEADER)?;

    let names: Vec<&str> = runtimes.iter().map(|r| r.as_str()).collect();
    writeln!(out, "Wrote {}", paths.config.display())?;
    writeln!(out, "Runtimes: {}", names.join(", "))?;
    for s in &skipped {
        writeln!(out, "Skipped:  {} ({})", s.runtime, state(s))?;
    }
    let pools: Vec<String> = config
        .pools
        .iter()
        .map(|(name, pool)| {
            format!(
                "{name}={}",
                pool.plan_tier
                    .map_or_else(|| "-".to_owned(), |t| t.to_string())
            )
        })
        .collect();
    writeln!(
        out,
        "Plans:    {} (change with --plan or by editing the file)",
        pools.join(", ")
    )?;
    writeln!(
        out,
        "Probes:   {} (change with: openchef quota probes on|off)",
        if probes { "on" } else { "off" }
    )?;
    writeln!(out, "Next:     openchef doctor")?;
    Ok(exit::OK)
}
